-- Doi chieu V0 vs V1: so dong, tong tien, tong phi
SELECT 'V0' v, COUNT(*) cnt, SUM(GD_AMT) tot_amt, SUM(FEE_AMT) tot_fee FROM RPT_POS_V0
UNION ALL
SELECT 'V1',   COUNT(*),     SUM(GD_AMT),         SUM(FEE_AMT)         FROM RPT_POS_V1;

-- MINUS 2 chieu (ky vong = 0)
SELECT COUNT(*) AS v0_not_in_v1 FROM (SELECT * FROM RPT_POS_V0 MINUS SELECT * FROM RPT_POS_V1);
SELECT COUNT(*) AS v1_not_in_v0 FROM (SELECT * FROM RPT_POS_V1 MINUS SELECT * FROM RPT_POS_V0);

-- Phi DVCNT: ban loop vs MERGE
SELECT COUNT(*) AS diff FROM (
  SELECT BC_DT, MID, TOT_AMT, FEE_AMT, VAT_AMT FROM RPT_FEE_LOOP
  MINUS
  SELECT BC_DT, MID, TOT_AMT, FEE_AMT, VAT_AMT FROM RPT_MERCHANT_FEE_WEEKLY);